class UserDocument(Base):
    """
    A bank statement the user uploaded to the Financial Document Checker.

    Privacy: the raw file is processed in memory and NEVER persisted. We store
    only the derived fields (`extracted`), the rule-engine result (`result`), and
    a sha256 of the original bytes (`content_hash`) for dedupe/audit — mirroring
    the SopReview hash-only approach. `extracted` holds applicant PII (balances,
    account holder, bank name) and is encrypted at the application layer before
    write via services/encryption.py (see the column note below).

    Lifecycle: a row is created at upload (status "parsed", result NULL); the
    evaluate step overwrites `extracted` with the user-confirmed values and fills
    `result` (status "evaluated"). Rows also serve as the daily usage log for
    entitlements/quotas (see services/entitlements.py).
    """
    __tablename__ = "user_documents"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    doc_type     = Column(String,  nullable=False, default="financial_statement")
    country      = Column(String,  nullable=True)
    bank_id      = Column(String,  nullable=True)        # detected bank slug, or NULL (generic)
    status       = Column(String,  nullable=False, default="parsed")  # parsed | evaluated
    content_hash = Column(String,  nullable=True)        # sha256 of the uploaded bytes

    # Parsed-then-confirmed statement (ParsedStatement.to_dict shape).
    # Encrypted at rest: stored as the Fernet envelope produced by
    # services.encryption.encrypt_json; read back via decrypt_json. PII — never
    # store this column as plaintext.
    extracted    = Column(JSON,    nullable=True)
    # financial_document_engine.evaluate(...) output. NULL until evaluated.
    result       = Column(JSON,    nullable=True)

    created_at   = Column(DateTime, default=utc_now_naive, nullable=False, index=True)
    updated_at   = Column(DateTime, default=utc_now_naive, nullable=False)


class VisaOutcome(Base):
    """
    A self-reported visa decision (Module 3: the outcome loop).

    Closes the loop from "here's your readiness score" to "here's what actually
    happened", which (a) lets us prove efficacy via approval-rate-by-score and
    (b) calibrates the engine. `score` is snapshotted from the linked check at
    report time so analytics survive deletion of the check.
    """
    __tablename__ = "visa_outcomes"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    # The readiness check this outcome relates to. SET NULL keeps the outcome (and
    # its snapshotted score) for analytics even if the check is later deleted.
    visa_check_id = Column(
        UUID(as_uuid=True),
        ForeignKey("visa_checks.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    country         = Column(String,  nullable=True)
    score           = Column(Integer, nullable=True)   # snapshot of the check's score
    outcome         = Column(String,  nullable=False)  # approved | refused | withdrawn | pending
    refusal_reasons = Column(JSON,    nullable=True)    # list[str], when refused
    decided_at      = Column(String,  nullable=True)    # ISO "YYYY-MM-DD" of the decision

    created_at      = Column(DateTime, default=utc_now_naive, nullable=False, index=True)
    updated_at      = Column(DateTime, default=utc_now_naive, nullable=False)


