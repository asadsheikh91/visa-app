class Report(Base):
    """
    A generated, downloadable Readiness Report (engine → Gemini narration → PDF).

    Persistence + determinism (constraint #4): a report is built and narrated ONCE
    at assessment time, then cached. `cache_key` = sha256(structured_engine_output
    + template_version + prompt_version); a rebuild with the same inputs finds this
    row and returns byte-identical data — the download path makes ZERO LLM calls.

    Access (constraint #7): `token` is an unguessable secret (secrets.token_urlsafe)
    and is the ONLY handle used in URLs — separate from the human-readable
    `report_id`, so report ids are never enumerable.

    PII (constraint #8): `data_encrypted` is the FULL ReportData payload (which
    includes the applicant's name and personal fields) stored as the Fernet
    envelope from services.encryption.encrypt_json — never plaintext at rest.
    """
    __tablename__ = "reports"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    # The readiness check this report was built from. SET NULL keeps the (already
    # rendered) report usable even if the underlying check is later deleted.
    visa_check_id = Column(
        UUID(as_uuid=True),
        ForeignKey("visa_checks.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # Human-readable id shown IN the report (e.g. "PV-CA-2026-0417"). NOT a URL key.
    report_id = Column(String, nullable=False, unique=True, index=True)
    # Unguessable access token — the only id that appears in URLs.
    token = Column(String, nullable=False, unique=True, index=True)

    # sha256(engine_output + template_version + prompt_version) — the cache key.
    cache_key        = Column(String, nullable=False, index=True)
    template_version = Column(String, nullable=False)
    prompt_version   = Column(String, nullable=False)
    # True when Gemini narration succeeded; False when deterministic fallback prose
    # was used (constraint #5). Observability only — the report is valid either way.
    narrated_by_ai   = Column(Boolean, nullable=False, default=False)

    # The full ReportData payload, Fernet-encrypted (see services.encryption). PII —
    # never store as plaintext.
    data_encrypted   = Column(JSON, nullable=False)

    created_at = Column(DateTime, default=utc_now_naive, nullable=False, index=True)


