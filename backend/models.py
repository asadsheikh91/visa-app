class VisaFile(Base):
    """
    A working visa document file for a user, generated by the checklist engine
    from their profile + a specific readiness check.

    One file per (user, visa_check) pair — see visa_file_service.fetch_or_create.
    `items` is the full checklist (list of item dicts); category progress and
    completion stats are derived from it at serialization time, never stored.
    """
    __tablename__ = "visa_files"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    # The readiness check this file was built from. SET NULL so deleting a check
    # leaves the file intact (its checklist is still useful).
    visa_check_id = Column(
        UUID(as_uuid=True),
        ForeignKey("visa_checks.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    country    = Column(String, nullable=False)
    visa_type  = Column(String, nullable=False, default="student_visa")

    # Full checklist: list of item dicts
    #   {id, title, category, priority, status, reason, guidance}
    items           = Column(JSON, nullable=False, default=list)

    # Persisted Financial Proof Checker evaluation: {inputs: {...}, result: {...}}
    # NULL for files created before Sprint 2.
    financial_proof  = Column(JSON, nullable=True)

    # Persisted Sponsor Evidence Module evaluation: {inputs: {...}, warnings: [...]}
    # NULL for files created before Sprint 2 or when not sponsor-funded.
    sponsor_evidence = Column(JSON, nullable=True)

    created_at = Column(DateTime, default=utc_now_naive, nullable=False)
    updated_at = Column(DateTime, default=utc_now_naive, nullable=False)


